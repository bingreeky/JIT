"""The shared per-unit runner: one engine behind every entry point.

A *unit* is one ``(case, rollout)`` pair. Running a unit means:

    1. build the benchmark adapter and pick the dataset item,
    2. obtain a harness -- generated by the meta model, or installed from a
       preset directory (best-of-N selection / seed harnesses),
    3. execute that harness against the case with the execution model,
    4. score the artifacts with the benchmark's evaluator,
    5. optionally repair-and-retry (``max_repairs``).

Steps 2-5 are ``jit``; this module owns everything around
it: isolation between concurrent units, artifact layout, resume, and the
score/summary files.

Artifacts under ``--output``::

    cases/<question_id>/rollout_<r>/report.json    full meta-agent report
    cases/<question_id>/rollout_<r>/harness/...   harness snapshot
    scores.jsonl                                   one line per unit
    summary.json                                   aggregate metrics
"""

from __future__ import annotations

import copy
import json
import re
import shutil
import threading
import time
import traceback
import uuid
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from . import metrics
from .config import REPO_ROOT

WORKSPACE_ROOT = REPO_ROOT / "scripts" / "workspaces"
RUNTIME_ROOT = REPO_ROOT / ".runtime"

# The five files that make up a harness.
HARNESS_FILES = ("memory.py", "planning.py", "action.py", "tool_policy.py", "prompt.yaml")


@dataclass
class RunOptions:
    """Everything that varies between a JIT run and a seed-harness run."""

    output: Path
    group_field: str = "group"
    metrics_profile: str = "generic"
    max_steps: int = 40
    max_repairs: int = 5
    rollouts: int = 1
    parallel_workers: int = 4
    repair_only_on_error: bool = True
    regenerate_on_error: bool = True

    # --- harness sourcing (mutually exclusive) --------------------------- #
    generate_only: bool = False
    """Stop right after generation: no execution, no scoring. Phase A of best-of-N."""

    harnesses_from: str = ""
    """Root of a --generate_only run; execute ``cases/<qid>/rollout_<r>/harness``."""

    selection: Dict[str, int] = field(default_factory=dict)
    """question_id -> chosen rollout, used with ``harnesses_from``."""

    preset_harness: str = ""
    """One fixed harness directory used for every case (seed-harness mode)."""

    # --- case selection ---------------------------------------------------- #
    max_samples: Optional[int] = None
    item_index: Optional[int] = None
    cases: Optional[List[str]] = None
    no_resume: bool = False

    # --- reporting --------------------------------------------------------- #
    label: str = ""
    """Free-form run label recorded in summary.json (e.g. the harness name)."""

    quiet: bool = False


# --------------------------------------------------------------------------- #
# Case identity
# --------------------------------------------------------------------------- #
def case_id(item: Dict[str, Any], item_index: int) -> str:
    """The id every artifact path and every best-of-N lookup must agree on.

    The benchmarks are inconsistent about the field name (office/odyssey carry
    ``task_id``, agentif/xbench carry ``question_id``, xbench/deepsearchqa carry
    neither), so one helper owns the fallback chain. A mismatch here makes
    ``harnesses_from`` miss its preset and silently regenerate instead.
    """
    return str(item.get("question_id") or item.get("task_id") or f"task_{item_index}")


def safe_case_id(item: Dict[str, Any], item_index: int) -> str:
    """The on-disk form of the case id.

    Artifacts live under ``cases/<sanitized id>/``, so ids carrying characters
    outside ``[A-Za-z0-9_.-]`` (odysseybench uses ``1-1:plus:0``) reach the
    selector only in sanitized form. Both spellings must resolve, or a
    ``--cases`` filter rejects every id and selection falls back to rollout 0.
    """
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", case_id(item, item_index))


def selected_rollout(selection: Dict[str, int], item: Dict[str, Any], item_index: int) -> int:
    """Chosen candidate for a case, accepting the raw or the sanitized id."""
    raw, safe = case_id(item, item_index), safe_case_id(item, item_index)
    return int(selection.get(raw, selection.get(safe, 0)))


# --------------------------------------------------------------------------- #
# Adapter construction
# --------------------------------------------------------------------------- #
def _adapter_kwargs(config: Dict[str, Any]) -> Dict[str, Any]:
    """The union of kwargs any adapter in the suite might want.

    ``_load_benchmark_adapter`` drops the ones the chosen adapter doesn't
    accept, so passing the union is safe:
        agentif / travel                 : judge_model / judge_api_base / judge_api_key
        odyssey                          : subset / memory_mode / rag_mode / top_k / ...
        travel                           : language
        shopping                         : level
    """
    benchmark_cfg = config.get("benchmark", {}) or {}
    judge_cfg = benchmark_cfg.get("judge", {}) or {}
    model_cfg = config.get("model", {}) or {}

    kwargs: Dict[str, Any] = {
        # Fall back to the execution model's credentials when no judge block
        # is given -- most providers serve both from the same endpoint.
        "judge_model": (
            judge_cfg.get("model_id") or judge_cfg.get("model") or model_cfg.get("model_id") or ""
        ),
        "judge_api_base": judge_cfg.get("api_base") or model_cfg.get("api_base") or "",
        "judge_api_key": judge_cfg.get("api_key") or model_cfg.get("api_key") or "",
    }
    if judge_cfg.get("max_tokens") is not None:
        kwargs["judge_max_tokens"] = judge_cfg["max_tokens"]
    for key in ("language", "level"):
        if benchmark_cfg.get(key) is not None:
            kwargs[key] = benchmark_cfg[key]
    kwargs.update(benchmark_cfg.get("adapter_kwargs", {}) or {})
    return kwargs


def make_adapter(config: Dict[str, Any], workspace_base: str = ""):
    """Build the benchmark adapter named in ``config.benchmark.name``."""
    from jit.harness_ops import _load_benchmark_adapter

    kwargs = _adapter_kwargs(config)
    if workspace_base:
        kwargs["workspace_base"] = workspace_base
    return _load_benchmark_adapter((config.get("benchmark", {}) or {}).get("name", ""), **kwargs)


def _workspace_name(item_index: int, rollout: int) -> str:
    return (
        f"harness_workspace_{item_index}_r{rollout}_"
        f"{threading.get_ident()}_{int(time.time() * 1000)}_{uuid.uuid4().hex[:8]}"
    )


# --------------------------------------------------------------------------- #
# One unit
# --------------------------------------------------------------------------- #
def _run_unit(
    base_config: Dict[str, Any],
    item_index: int,
    rollout: int,
    opts: RunOptions,
    cases_dir: Path,
) -> Dict[str, Any]:
    """Obtain a harness for one (case, rollout), execute it, and score it."""
    from jit.meta_agent import MetaReActAgent
    from jit.schemas import MetaAgentRequest

    config = copy.deepcopy(base_config)
    benchmark_cfg = config.get("benchmark", {})
    bench_name = benchmark_cfg.get("name", "bench")

    # Per-rollout scratch dir: concurrent rollouts of the same task must never
    # share (and race on) the adapter's question_id-keyed workspace.
    task_ws_base = str(
        RUNTIME_ROOT / "workspace" / f"{bench_name}_eval"
        / f"{item_index}_r{rollout}_{uuid.uuid4().hex[:8]}"
    )
    adapter = make_adapter(config, workspace_base=task_ws_base)
    dataset = adapter.load_dataset(benchmark_cfg.get("dataset_path", ""))
    item = dataset[item_index]

    run_tools = list(config.get("tools", []) or [])
    for tool_name in adapter.get_tools() or []:
        if tool_name not in run_tools:
            run_tools.append(tool_name)

    workspace_name = _workspace_name(item_index, rollout)
    workspace_dir = WORKSPACE_ROOT / workspace_name
    if workspace_dir.exists():
        shutil.rmtree(workspace_dir)
    workspace_dir.mkdir(parents=True, exist_ok=True)

    # Where the harness comes from, if not generated.
    preset_dir = ""
    if opts.preset_harness:
        preset_dir = opts.preset_harness
    elif opts.harnesses_from:
        rid = selected_rollout(opts.selection, item, item_index)
        preset_dir = str(
            Path(opts.harnesses_from) / "cases" / safe_case_id(item, item_index)
            / f"rollout_{rid}" / "harness"
        )

    error = ""
    report: Dict[str, Any] = {}
    try:
        request = MetaAgentRequest(
            benchmark_adapter=adapter,
            item=item,
            tools=run_tools,
            max_steps=opts.max_steps,
            max_repairs=opts.max_repairs,
            repair_only_on_error=opts.repair_only_on_error,
            regenerate_on_error=opts.regenerate_on_error,
            benchmark_config=benchmark_cfg,
            generate_only=opts.generate_only,
            preset_harness_dir=preset_dir,
        )
        agent = MetaReActAgent(
            model=config.get("meta_model", {}),
            config=config,
            workspace_name=workspace_name,
        )
        report = agent.run(request).to_dict()
    except Exception as exc:  # noqa: BLE001 - record and continue with the next unit
        error = f"{exc}\n{traceback.format_exc()}"

    # Persist artifacts: report.json + harness snapshot, namespaced per rollout.
    case_dir = cases_dir / safe_case_id(item, item_index) / f"rollout_{rollout}"
    case_dir.mkdir(parents=True, exist_ok=True)
    report_path = case_dir / "report.json"
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")

    harness_dst = case_dir / "harness"
    if harness_dst.exists():
        shutil.rmtree(harness_dst)
    if workspace_dir.exists():
        shutil.copytree(workspace_dir, harness_dst, ignore=shutil.ignore_patterns("__pycache__"))
        shutil.rmtree(workspace_dir, ignore_errors=True)

    shutil.rmtree(task_ws_base, ignore_errors=True)

    return metrics.summarize_case(
        opts.metrics_profile,
        item,
        item_index,
        rollout,
        case_id(item, item_index),
        str(item.get(opts.group_field, "")),
        report,
        str(report_path),
        error=error,
    )


# --------------------------------------------------------------------------- #
# Case selection + resume
# --------------------------------------------------------------------------- #
def _resolve_indices(dataset: List[Dict[str, Any]], opts: RunOptions) -> List[int]:
    if opts.item_index is not None:
        return [opts.item_index]
    indices = list(range(len(dataset)))
    if opts.max_samples is not None:
        indices = indices[: opts.max_samples]
    if opts.cases:
        wanted = {c.strip() for c in opts.cases if c.strip()}
        indices = [
            i
            for i in indices
            if case_id(dataset[i], i) in wanted or safe_case_id(dataset[i], i) in wanted
        ]
        found = {case_id(dataset[i], i) for i in indices} | {
            safe_case_id(dataset[i], i) for i in indices
        }
        if wanted - found:
            raise SystemExit(f"--cases ids not in dataset: {sorted(wanted - found)[:5]}")
    return indices


def _check_presets(dataset: List[Dict[str, Any]], indices: List[int], opts: RunOptions) -> None:
    """Fail fast when a selected preset harness is missing.

    Without this, ``selection``'s "unknown id defaults to rollout 0" would
    silently turn a best-of-N run back into a plain rollout-0 run.
    """
    if not opts.harnesses_from:
        return
    if not (Path(opts.harnesses_from) / "cases").is_dir():
        raise SystemExit(f"harnesses_from has no cases/ dir: {opts.harnesses_from}")
    missing = []
    for idx in indices:
        rid = selected_rollout(opts.selection, dataset[idx], idx)
        path = (
            Path(opts.harnesses_from) / "cases" / safe_case_id(dataset[idx], idx)
            / f"rollout_{rid}" / "harness"
        )
        # An EMPTY harness dir is the dangerous case: the preset install then
        # copies 0/5 files, the meta-agent sees an incomplete workspace and
        # quietly regenerates from scratch -- turning a best-of-N run into a
        # plain single-shot run that still reports as best-of-N.
        absent = [f for f in HARNESS_FILES if not (path / f).is_file()]
        if absent:
            missing.append(
                f"{case_id(dataset[idx], idx)} -> rollout_{rid} "
                f"({'no dir' if not path.is_dir() else 'missing ' + ','.join(absent)})"
            )
    if missing:
        raise SystemExit(
            f"harnesses_from is missing {len(missing)}/{len(indices)} preset harnesses, e.g. "
            + "; ".join(missing[:5])
            + "\nGeneration did not produce usable candidates for these cases; "
            "re-run the generate phase rather than executing an empty preset."
        )


def _load_resumable(
    dataset: List[Dict[str, Any]],
    units: List[Tuple[int, int]],
    cases_dir: Path,
    opts: RunOptions,
) -> Tuple[List[Dict[str, Any]], List[Tuple[int, int]]]:
    """Split units into (already good, still to run) using their report.json."""
    kept: List[Dict[str, Any]] = []
    pending: List[Tuple[int, int]] = []
    for idx, rollout in units:
        item = dataset[idx]
        report_path = cases_dir / safe_case_id(item, idx) / f"rollout_{rollout}" / "report.json"
        report = None
        if report_path.exists():
            try:
                report = json.loads(report_path.read_text(encoding="utf-8"))
            except Exception:  # noqa: BLE001 - a truncated report just means re-run
                report = None
        record = (
            metrics.summarize_case(
                opts.metrics_profile,
                item,
                idx,
                rollout,
                case_id(item, idx),
                str(item.get(opts.group_field, "")),
                report,
                str(report_path),
            )
            if report
            else {}
        )
        if report and not metrics.should_rerun(report, record):
            kept.append(record)
        else:
            pending.append((idx, rollout))
    return kept, pending


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #
def run(config: Dict[str, Any], opts: RunOptions) -> Dict[str, Any]:
    """Run every (case, rollout) unit and write scores.jsonl + summary.json."""
    benchmark_cfg = config.get("benchmark", {})

    def log(message: str) -> None:
        if not opts.quiet:
            print(message, flush=True)

    probe = make_adapter(config)
    dataset = probe.load_dataset(benchmark_cfg.get("dataset_path", ""))
    if not dataset:
        raise SystemExit(f"empty dataset at {benchmark_cfg.get('dataset_path', '')}")

    indices = _resolve_indices(dataset, opts)
    _check_presets(dataset, indices, opts)

    rollouts = max(1, int(opts.rollouts))
    units = [(idx, r) for idx in indices for r in range(rollouts)]

    output_root = Path(opts.output)
    cases_dir = output_root / "cases"
    cases_dir.mkdir(parents=True, exist_ok=True)
    scores_path = output_root / "scores.jsonl"
    summary_path = output_root / "summary.json"

    results: List[Dict[str, Any]] = []
    run_units = list(units)
    if not opts.no_resume:
        results, run_units = _load_resumable(dataset, units, cases_dir, opts)
        log(f"[eval] resume: {len(results)} kept, {len(run_units)} to (re)run")

    log(
        f"[eval] benchmark={benchmark_cfg.get('name')}"
        f" | meta={(config.get('meta_model') or {}).get('model_id', '-')}"
        f"@{(config.get('meta_model') or {}).get('api_base', '-')}"
        f" | exec={config.get('model', {}).get('model_id', '-')}"
        f" | judge={(benchmark_cfg.get('judge') or {}).get('model_id', '-')}"
        f" | cases={len(indices)} x rollouts={rollouts} = {len(units)} units"
        f" (running {len(run_units)})"
        f" | workers={opts.parallel_workers} | max_repairs={opts.max_repairs}"
    )

    scores_lock = threading.Lock()
    with scores_path.open("w", encoding="utf-8") as scores_file:
        for record in results:
            scores_file.write(json.dumps(record, ensure_ascii=False) + "\n")
        scores_file.flush()

        workers = max(1, min(opts.parallel_workers, len(run_units))) if run_units else 1
        done = 0
        with ThreadPoolExecutor(max_workers=workers) as executor:
            future_to_unit = {
                executor.submit(_run_unit, config, idx, r, opts, cases_dir): (idx, r)
                for idx, r in run_units
            }
            for future in as_completed(future_to_unit):
                idx, rollout = future_to_unit[future]
                try:
                    record = future.result()
                except Exception as exc:  # noqa: BLE001
                    item = dataset[idx]
                    record = metrics.empty_record(
                        idx,
                        rollout,
                        case_id(item, idx),
                        str(item.get(opts.group_field, "")),
                        str(exc),
                    )
                results.append(record)
                with scores_lock:
                    scores_file.write(json.dumps(record, ensure_ascii=False) + "\n")
                    scores_file.flush()
                done += 1
                log(
                    f"[eval] ({done}/{len(run_units)}) {record.get('question_id')}"
                    f" r{record.get('rollout')} score={float(record.get('score', 0.0)):.3f}"
                    f" pass={record.get('is_pass')}"
                    + (f" err={str(record['run_error'])[:120]}" if record.get("run_error") else "")
                )

    results.sort(key=lambda r: (int(r.get("item_index", -1)), int(r.get("rollout", -1))))
    summary = {
        "benchmark": benchmark_cfg.get("name", ""),
        "label": opts.label,
        "dataset_path": benchmark_cfg.get("dataset_path", ""),
        "meta_agent_model": (config.get("meta_model") or {}).get("model_id", ""),
        "meta_agent_base": (config.get("meta_model") or {}).get("api_base", ""),
        "meta_agent_temperature": (config.get("meta_model") or {}).get("temperature", None),
        "execution_model": config.get("model", {}).get("model_id", ""),
        "judge_model": (benchmark_cfg.get("judge") or {}).get("model_id", ""),
        "metrics_profile": opts.metrics_profile,
        "max_steps": opts.max_steps,
        "max_repairs": opts.max_repairs,
        "rollouts": rollouts,
        "total_units": len(results),
        "total_cases": len({str(r.get("question_id", "")) for r in results}),
        "per_rollout_metrics": metrics.aggregate_per_rollout(opts.metrics_profile, results),
        "per_case_metrics": metrics.aggregate_per_case(opts.metrics_profile, results),
        "scores_path": str(scores_path),
    }
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    log("\n[eval] DONE")
    log("[eval] per-rollout metrics:")
    log(json.dumps(summary["per_rollout_metrics"], ensure_ascii=False, indent=2))
    log("[eval] per-case metrics (best-of-k / pass@k):")
    log(json.dumps(summary["per_case_metrics"], ensure_ascii=False, indent=2))
    log(f"[eval] per-unit scores : {scores_path}")
    log(f"[eval] summary         : {summary_path}")
    log(f"[eval] per-unit reports: {cases_dir}/<question_id>/rollout_<r>/report.json")
    return summary


def count_infra_failures(output_root: Path) -> int:
    """Units whose failure was infrastructure, not the model -- worth retrying."""
    scores_path = Path(output_root) / "scores.jsonl"
    if not scores_path.is_file():
        return 0
    total = 0
    for line in scores_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        if metrics.is_infra_failure(
            f"{record.get('run_error', '')} {record.get('validation_error', '')}"
        ):
            total += 1
    return total
